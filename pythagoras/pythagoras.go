// Package pythagoras provides Pythagorean triplets: integers a < b < c with
// a² + b² = c², as a type, a test, and streams generated with Euclid's
// formula.
package pythagoras

import (
	"github.com/t1sk3/go-utils/stream"
	"github.com/t1sk3/go-utils/types/constraints"
)

// Triplet is a Pythagorean triplet with A < B < C. It is comparable, so it
// can be used as a map key.
type Triplet[E constraints.Integer] struct{ A, B, C E }

// Perimeter returns A + B + C.
func (t Triplet[E]) Perimeter() E { return t.A + t.B + t.C }

// Scale returns the triplet (kA, kB, kC).
func (t Triplet[E]) Scale(k E) Triplet[E] { return Triplet[E]{k * t.A, k * t.B, k * t.C} }

// IsTriplet reports whether a² + b² = c². It overflows E silently for large
// arguments.
func IsTriplet[E constraints.Integer](a, b, c E) bool {
	return a*a+b*b == c*c
}

// PrimitiveTriplets returns every primitive triplet (gcd(A, B, C) = 1) with
// C <= maxC, using Euclid's formula: for m > n > 0, coprime and of opposite
// parity, (m²-n², 2mn, m²+n²) with the two legs ordered so A < B. The
// order is by generator (m, then n), not sorted; use Sorted if you need an
// order.
func PrimitiveTriplets[E constraints.Integer](maxC E) stream.Stream[Triplet[E]] {
	return stream.FromSeq(func(yield func(Triplet[E]) bool) {
		// Written so that nothing overflows E: euclid keeps m*m <= maxC.
		euclid(maxC, func(m, n E) bool { return n*n <= maxC-m*m }, yield)
	})
}

// TripletsWithPerimeterAtMost returns every triplet, primitive or not, with
// A + B + C <= p (Project Euler #39 and #75): each primitive triplet
// followed by its multiples. The order is by generator, not sorted, and no
// triplet appears twice.
func TripletsWithPerimeterAtMost[E constraints.Integer](p E) stream.Stream[Triplet[E]] {
	return stream.FromSeq(func(yield func(Triplet[E]) bool) {
		// The perimeter of Euclid's triplet is 2m(m+n); 2m(m+n) <= p is
		// tested as m+n <= floor(floor(p/2)/m) so that nothing overflows E.
		euclid(p, func(m, n E) bool { return m+n <= p/2/m }, func(t Triplet[E]) bool {
			per := t.Perimeter()
			for k := E(1); k <= p/per; k++ {
				if !yield(t.Scale(k)) {
					return false
				}
			}
			return true
		})
	})
}

// euclid yields the primitive triplets generated by (m, n) for which fits
// holds. fits must be monotonic in both m and n, and bound is an upper
// bound for m*m that keeps the loop finite. fits is only called with
// n < m and m*m <= bound, and must not overflow E for those.
func euclid[E constraints.Integer](bound E, fits func(m, n E) bool, yield func(Triplet[E]) bool) {
	for m := E(2); m <= bound/m && fits(m, 1); m++ {
		for n := E(1); n < m; n++ {
			if !fits(m, n) {
				break
			}
			if (m-n)%2 == 0 || gcd(m, n) != 1 {
				continue
			}
			a, b := m*m-n*n, 2*m*n
			if a > b {
				a, b = b, a
			}
			if !yield(Triplet[E]{a, b, m*m + n*n}) {
				return
			}
		}
	}
}

func gcd[E constraints.Integer](a, b E) E {
	for b != 0 {
		a, b = b, a%b
	}
	return a
}
